from typing import Any, Dict, FrozenSet, List, Optional, Tuple

import structlog
from gitlab_cloud_connector import GitLabUnitPrimitive

from lib.billing_events.context import REALM_MAPPING
from lib.events.base import FeatureQualifiedNameStatic
from lib.internal_events.context import EventContext

__all__ = [
    "billable_feature_for_unit_primitive",
    "is_billing_validation_enforced",
    "validate_billing_event_context",
]

log = structlog.stdlib.get_logger("billing_events_validation")

# Always-required fields per the billable_usage schema SSOT:
# https://gitlab.com/gitlab-org/iglu/-/blob/a2cc6f7593fcfbddf570f0331f0ec453eefedd1b/public/schemas/com.gitlab/billable_usage/jsonschema/1-1-0
# `event_id`, `event_type`, `unit_of_measure` and `timestamp` are also always
# required, but they are generated by `BillingEventsClient.track_billing_event`
# at track time, so only `realm` can be checked from the request context.
_ALWAYS_REQUIRED_CONTEXT_FIELDS: Tuple[str, ...] = ("realm",)

# Dedicated is not a schema realm; for validation it follows the SaaS rule.
# The billing client still sends it as-is, so this stays validation-only.
_VALIDATION_REALM_MAPPING: Dict[str, str] = {
    **REALM_MAPPING,
    "dedicated": "SaaS",
    "Dedicated": "SaaS",
}

# Realm-dependent required fields (schema oneOf), keyed by normalized realm.
# Names refer to `EventContext` attributes; `ultimate_parent_namespace_id` maps
# to `root_namespace_id` in the billing context.
_REALM_REQUIRED_FIELDS: Dict[str, Tuple[str, ...]] = {
    "SM": ("instance_id", "unique_instance_id"),
    "SaaS": ("ultimate_parent_namespace_id",),
}

# AI Gateway unit primitives that can emit a billing event, and the feature their
# billing event is reported under.
_FEATURE_BY_UNIT_PRIMITIVE: Dict[GitLabUnitPrimitive, str] = {
    GitLabUnitPrimitive.COMPLETE_CODE: FeatureQualifiedNameStatic.CODE_SUGGESTIONS,
    GitLabUnitPrimitive.GENERATE_CODE: FeatureQualifiedNameStatic.CODE_SUGGESTIONS,
    GitLabUnitPrimitive.AI_GATEWAY_MODEL_PROVIDER_PROXY: FeatureQualifiedNameStatic.AIGW_PROXY_USE,
}

# Features whose requests are rejected when mandatory fields are missing and the
# validation mode is `enforce`. Add a feature_qualified_name once its requests send every field.
_ENFORCED_FEATURE_QUALIFIED_NAMES: FrozenSet[str] = frozenset()


def billable_feature_for_unit_primitive(
    user: Any, unit_primitive: Optional[str]
) -> Optional[str]:
    """Return the billed feature of the request's unit primitive, or None when the request is not billable.

    The unit primitive comes from a client header, so it only counts when the signed token grants it.
    """
    if not unit_primitive or unit_primitive not in _FEATURE_BY_UNIT_PRIMITIVE:
        return None

    unit_primitive = GitLabUnitPrimitive(unit_primitive)
    can = getattr(user, "can", None)
    if not (can and can(unit_primitive)):
        return None

    return _FEATURE_BY_UNIT_PRIMITIVE[unit_primitive]


def is_billing_validation_enforced(mode: str, feature_qualified_name: str) -> bool:
    """Return whether missing mandatory fields must reject a request for the feature."""
    feature_name = feature_qualified_name.split("/", 1)[0]
    return mode == "enforce" and feature_name in _ENFORCED_FEATURE_QUALIFIED_NAMES


def _is_empty(value: Any) -> bool:
    return value is None or (isinstance(value, str) and value == "")


def _validation_realm(realm: Optional[str]) -> Optional[str]:
    if not realm:
        return realm
    return _VALIDATION_REALM_MAPPING.get(realm, realm)


def _missing_fields(context: EventContext) -> List[str]:
    realm = _validation_realm(context.realm) or ""
    required_fields = _ALWAYS_REQUIRED_CONTEXT_FIELDS + _REALM_REQUIRED_FIELDS.get(
        realm, ()
    )

    return [
        field_name
        for field_name in required_fields
        if _is_empty(getattr(context, field_name, None))
    ]


def validate_billing_event_context(
    context: EventContext,
    feature_qualified_name: str,
    enforce: bool,
    logger: Optional[Any] = None,
    **location: Any,
) -> List[str]:
    """Check the request context for fields that billing events require.

    Meant to run before the request is processed, so invalid requests can be rejected before any cost-incurring 3rd
    party LLM call. Logs an error when ``enforce`` is set and a warning otherwise.

    Args:
        context: The request's EventContext.
        feature_qualified_name: The feature the request's billing event is reported under.
        enforce: Whether the caller rejects the request when fields are missing.
        logger: Structlog logger to use. Defaults to this module's logger.
        **location: Extra kwargs added to the log line (e.g. ``endpoint="/v2/code/completions"``).

    Returns:
        The names of the missing mandatory fields. Empty when the context is valid.
    """
    missing = _missing_fields(context)
    if not missing:
        return missing

    logger = logger or log
    log_method = logger.error if enforce else logger.warning
    log_method(
        "Billing event context missing mandatory fields",
        missing_fields=missing,
        feature_qualified_name=feature_qualified_name,
        realm=_validation_realm(context.realm),
        deployment_type=context.deployment_type,
        instance_version=context.instance_version,
        client_type=context.client_type,
        client_name=context.client_name,
        enforced=enforce,
        correlation_id=context.correlation_id,
        **location,
    )

    return missing
